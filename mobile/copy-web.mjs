// Copies the website (DanfossHackathon/frontend) into www/, which Capacitor packs into the app.
// The website is NOT duplicated in git: edit DanfossHackathon/frontend and run `npm run sync`.
//
// Optional: BACKEND_URL=https://... npm run sync   → the app starts with that backend address
// (users can still change it under "Server" in the app).
import { cpSync, rmSync, writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "DanfossHackathon", "frontend");
const out = join(here, "www");

rmSync(out, { recursive: true, force: true });
cpSync(src, out, {
  recursive: true,
  filter: (p) => !p.endsWith("README.md") && !p.includes(`${"/"}examples`),
});

const backend = (process.env.BACKEND_URL || "").trim();
writeFileSync(join(out, "js", "mobile-defaults.js"),
  `// generated by mobile/copy-web.mjs\nwindow.MOBILE_DEFAULT_SERVER = ${JSON.stringify(backend)};\n`);

// load the defaults right after config.js (only in the app copy)
const indexPath = join(out, "index.html");
const html = readFileSync(indexPath, "utf8");
const tag = '<script src="js/config.js"></script>';
if (!html.includes(tag)) throw new Error("index.html no longer loads js/config.js – update copy-web.mjs");
writeFileSync(indexPath, html.replace(tag, tag + '\n  <script src="js/mobile-defaults.js"></script>'));

console.log(`Copied website to www/ (default backend: ${backend || "none, asked on first start"})`);
